# 방문객 추세 배율 r: 보정값 a(로그)를 log(1 + r*(e^a - 1))로 바꿔 '추가 승차 인원'을 r배 한다.
# 근거(주최 측 발표, 언론 보도):
#  능허대: 2023 8만(2일) · 2024 약 10만(3일) · 2025 7.2만(3일) · 2026 12만(2일, 연수한마음공원).
#          보정 근거인 2026-03 봄축제(같은 장소)는 방문객 발표 없음. 하루 6만 명으로 역대 최대 → 1.5배 (보수적)
#  부평풍물: 2023 50만(거리 2일) · 2024 60만(거리 2일) · 2025 45만(3일). 2026 30주년, 인원 미발표 → 3년 평균/2025 ≈ 1.15 → 1.1배
#  송도해변: 2024 6.5만 · 2025 7만(7일) · 2026 7.3만(8일, 하루 평균은 0.91배) → 1.0배
#  드림파크·계양 가을꽃: 방문객 발표 없음 → 1.0배 (계양은 2026 일정 미확정이라 이미 0.6배)
TREND = {"연수 능허대": 1.5, "부평풍물대축제": 1.1}

def trend_of(name):
    return next((r for k, r in TREND.items() if name.startswith(k)), 1.0)

def adjust(sub, test):
    k = test[["example_id", "date", "station_id", "hour"]].merge(sub, on="example_id", how="left")
    k["date"] = pd.to_datetime(k["date"]); lp = np.log1p(k["boardings"].to_numpy(dtype=float)); n = 0
    for name, st, days, prof in RULES:
        m = (k.station_id == st) & k.date.isin(pd.to_datetime(days)) & k.hour.isin(list(prof))
        a = k.loc[m, "hour"].map(prof).to_numpy(); r = trend_of(name)
        lp[m.to_numpy()] += np.log1p(r * np.expm1(a)); n += int(m.sum())
    k["boardings"] = np.expm1(lp)
    return sub[["example_id"]].merge(k[["example_id", "boardings"]], on="example_id", how="left"), n

